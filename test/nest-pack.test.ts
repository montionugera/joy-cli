import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import { execSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { runCli } from '../src/cli.js';

describe('Track S2: nest pack (entity-spec, dto, entity, repo, service, controller, module, resource, test)', () => {
  let tmpDir: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'joy-cli-s2-'));
    fs.mkdirSync(path.join(tmpDir, 'src/modules/main'), { recursive: true });
    fs.writeFileSync(
      path.join(tmpDir, 'package.json'),
      JSON.stringify(
        {
          name: 'fixture-nest',
          dependencies: {
            '@nestjs/common': '^10.4.1',
            '@nestjs/core': '^10.4.1',
            '@nestjs/typeorm': '^10.0.2',
            '@montionugera/entity-spec': '^2.0.28',
            '@montionugera/entity-spec-gen-zod': '^2.0.28',
            '@montionugera/entity-spec-gen-openapi': '^2.0.28',
            '@montionugera/server-decorator': '^2.0.28',
            typeorm: '^0.3.25',
            zod: '^3.24.0',
          },
          scripts: {
            build: 'node -e "process.exit(0)"',
            test: 'node -e "process.exit(0)"',
          },
        },
        null,
        2
      )
    );
    fs.writeFileSync(
      path.join(tmpDir, 'src/modules/main/app.module.ts'),
      `import { Module } from '@nestjs/common';\nimport { ContentModule } from '../content/content.module';\n\n@Module({\n  imports: [\n    ContentModule,\n  ],\n})\nexport class AppModule {}\n`
    );
  });

  afterEach(() => {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  it('scaffolds full resource Invoice with EntitySpec, runtime Zod/OpenAPI DTO, TypeORM columns, Repo, Service, Controller, and AppModule registration', async () => {
    expect(await runCli(['init'], tmpDir)).toBe(0);
    expect(
      await runCli(
        [
          'g',
          'resource',
          'Invoice',
          '--fields',
          'number:str,total:float,paid:bool=false,status:enum(draft|sent)',
          '--no-verify',
        ],
        tmpDir
      )
    ).toBe(0);

    const specCode = fs.readFileSync(
      path.join(tmpDir, 'src/modules/invoice/invoice.entity-spec.ts'),
      'utf8'
    );
    expect(specCode).toContain("@Restful({ path: 'invoices' })");
    expect(specCode).toContain('@str()');
    expect(specCode).toContain('@float()');
    expect(specCode).toContain("@enumOf(['draft', 'sent'])");

    const dtoCode = fs.readFileSync(
      path.join(tmpDir, 'src/modules/invoice/dto/invoice.dto.ts'),
      'utf8'
    );
    expect(dtoCode.startsWith('// @generated by @montionugera/joy-cli — DO NOT EDIT')).toBe(
      true
    );
    expect(dtoCode).toContain('createSchema(InvoiceEntitySpec)');
    expect(dtoCode).toContain('openapiComponents(InvoiceEntitySpec)');
    expect(dtoCode).toContain('openapiPaths(InvoiceEntitySpec)');

    const entityCode = fs.readFileSync(
      path.join(tmpDir, 'src/modules/invoice/invoice.entity.ts'),
      'utf8'
    );
    expect(entityCode).toContain("@Column({ type: 'varchar' })");
    expect(entityCode).toContain("@Column({ type: 'double precision' })");
    expect(entityCode).toContain("@Column({ type: 'boolean', default: false })");

    const repoCode = fs.readFileSync(
      path.join(tmpDir, 'src/modules/invoice/invoice.repository.ts'),
      'utf8'
    );
    expect(repoCode).toContain('@InjectRepository(InvoiceEntity)');
    expect(repoCode).toContain('Repository<InvoiceEntity>');

    const appModule = fs.readFileSync(
      path.join(tmpDir, 'src/modules/main/app.module.ts'),
      'utf8'
    );
    expect(appModule).toContain(`import { InvoiceModule } from '../invoice/invoice.module';`);
    expect(appModule).toContain('InvoiceModule,');

    // --check on unmodified DTO exits 0 (without needing --fields repeated)
    expect(await runCli(['g', 'dto', 'Invoice', '--check'], tmpDir)).toBe(0);

    // Mutating @generated DTO causes --check to exit 2 (E_DRIFT)
    const dtoFile = path.join(tmpDir, 'src/modules/invoice/dto/invoice.dto.ts');
    fs.appendFileSync(dtoFile, '\n// drift\n');
    expect(await runCli(['g', 'dto', 'Invoice', '--check'], tmpDir)).toBe(2);

    // Re-running joy g dto Invoice restores canonical file and exits 0
    expect(await runCli(['g', 'dto', 'Invoice', '--no-verify'], tmpDir)).toBe(0);
    expect(await runCli(['g', 'dto', 'Invoice', '--check'], tmpDir)).toBe(0);

    // joy verify resource Invoice exits 0
    expect(await runCli(['verify', 'resource', 'Invoice'], tmpDir)).toBe(0);

    // joy doctor exits 0
    expect(await runCli(['doctor', '--strict'], tmpDir)).toBe(0);

    // joy g test on existing service file -> creates sibling .spec.ts
    fs.writeFileSync(
      path.join(tmpDir, 'src/modules/invoice/helper.ts'),
      'export const calc = (n: number) => n * 2;\n'
    );
    expect(
      await runCli(['g', 'test', 'src/modules/invoice/helper.ts', '--no-verify'], tmpDir)
    ).toBe(0);
    expect(fs.existsSync(path.join(tmpDir, 'src/modules/invoice/helper.spec.ts'))).toBe(true);
  });

  it('executes runtime EntitySpec + gen-zod + gen-openapi validation against node-server-decorator packages', async () => {
    const nsdEntityDist =
      '/Users/pasitnusso/workspace/repos/node-server-decorator/node/packages/entity/dist/index.js';
    const nsdZodDist =
      '/Users/pasitnusso/workspace/repos/node-server-decorator/node/packages/gen-zod/dist/index.js';
    const nsdOpenApiDist =
      '/Users/pasitnusso/workspace/repos/node-server-decorator/node/packages/gen-openapi/dist/index.js';
    if (!fs.existsSync(nsdEntityDist)) return;

    const req = createRequire(import.meta.url);
    const entityMod = req(nsdEntityDist);
    const zodMod = req(nsdZodDist);
    const openApiMod = req(nsdOpenApiDist);

    // Build the exact runtime spec that generated InvoiceSpec produces (@id(), @str(), @float(), @bool(), @enumOf(...))
    class InvoiceSpec {
      id!: string;
      number!: string;
      total!: number;
      paid!: boolean;
      status!: 'draft' | 'sent';
    }
    entityMod.id()(InvoiceSpec.prototype, 'id');
    entityMod.str()(InvoiceSpec.prototype, 'number');
    entityMod.float()(InvoiceSpec.prototype, 'total');
    entityMod.bool()(InvoiceSpec.prototype, 'paid');
    entityMod.enumOf(['draft', 'sent'])(InvoiceSpec.prototype, 'status');
    entityMod.Restful({ path: 'invoices' })(InvoiceSpec);

    const spec = entityMod.entitySpec(InvoiceSpec);
    expect(spec.specVersion).toBe('1.2.0');
    expect(spec.entity).toBe('InvoiceSpec');
    expect(spec.fields).toHaveLength(5);

    // Note: id() sets readonly: true, so CreateInvoiceSchema excludes 'id'!
    const CreateInvoiceSchema = zodMod.createSchema(spec);
    const valid = CreateInvoiceSchema.safeParse({
      number: 'INV-001',
      total: 125.5,
      paid: false,
      status: 'draft',
    });
    expect(valid.success).toBe(true);

    const invalid = CreateInvoiceSchema.safeParse({
      number: 'INV-001',
      total: 'not-a-float',
      paid: false,
      status: 'unknown',
    });
    expect(invalid.success).toBe(false);

    const components = openApiMod.openapiComponents(spec);
    const paths = openApiMod.openapiPaths(spec);
    expect(components.schemas['InvoiceSpecCreate']).toBeDefined();
    expect(paths['/invoices']).toBeDefined();
  });

  it('runs non-destructive --dry-run smoke check against real content-svc repo', async () => {
    const contentSvcDir = '/Users/pasitnusso/workspace/repos/content-svc';
    if (!fs.existsSync(contentSvcDir)) return;
    const beforeStatus = execSync('git status --porcelain', {
      cwd: contentSvcDir,
      encoding: 'utf8',
    });
    expect(await runCli(['init', '--dry-run'], contentSvcDir)).toBe(0);
    // Generator without anchors installed in content-svc fails safely with exit 1 (E_ANCHOR_MISSING) and writes nothing
    expect(
      await runCli(
        ['g', 'resource', 'Invoice', '--fields', 'number:str,total:float', '--dry-run'],
        contentSvcDir
      )
    ).toBe(1);
    // Generator that does not require AppModule anchors (entity-spec) succeeds in --dry-run with exit 0
    expect(
      await runCli(
        ['g', 'entity-spec', 'Invoice', '--fields', 'number:str,total:float', '--dry-run'],
        contentSvcDir
      )
    ).toBe(0);
    const afterStatus = execSync('git status --porcelain', {
      cwd: contentSvcDir,
      encoding: 'utf8',
    });
    expect(afterStatus).toBe(beforeStatus);
  });
});
